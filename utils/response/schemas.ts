// utils/response/schemas.ts
/**
 * Response types and schemas following RFC 7807 (Problem Details) and success envelopes
 * 
 * Architecture:
 * - Everything is a Zod schema first
 * - Types are derived from schemas via z.input and z.output
 * - Factory functions create generic schemas (like in fields.ts, filtering.ts)
 * - Follows same pattern as query processing utilities
 * - Aligns with Hono's ContentfulStatusCode and ContentlessStatusCode types
 */
import type { ContentfulStatusCode } from 'hono/utils/http-status'
import { ContentfulStatusCodeSchema, ContentlessStatusCodeSchema } from './status-codes.ts'
import { z } from 'zod'

/**
 * Validation error detail schema.
 */
export const ValidationErrorDetailSchema = z.object({
  field: z.string(),
  message: z.string(),
})

/**
 * One field-level validation failure inferred from the schema.
 */
export type ValidationErrorDetail = z.output<typeof ValidationErrorDetailSchema>

/**
 * Canonical JSON content type for successful API envelopes.
 */
export const JSON_CONTENT_TYPE = 'application/json' as const

/**
 * Canonical JSON content type for RFC 7807 problem responses.
 */
export const PROBLEM_JSON_CONTENT_TYPE = 'application/problem+json' as const

/**
 * RFC 7807 problem-details base schema.
 */
export const ProblemDetailsSchema = z.object({
  type: z.string().describe('A URI reference that identifies the problem type.'),
  title: z.string().describe('A short, human-readable summary of the problem type.'),
  status: ContentfulStatusCodeSchema.describe('The HTTP status code generated by the origin server for this occurrence of the problem.'),
  detail: z.string().describe('A human-readable request specific explanation to this occurrence of the problem.'),
  instance: z.string().describe('A URI reference that identifies the specific occurrence of the problem.'),
  timestamp: z.coerce.date().describe('The time at which the problem occurred.'),
  docs: z.url().optional().describe('A URL pointing to documentation about this problem type.'),
}).catchall(z.unknown())

/**
 * RFC 7807 problem-details payload inferred from the schema.
 */
export type ProblemDetails = z.output<typeof ProblemDetailsSchema>

/**
 * RFC 7807 problem-details schema with validation errors.
 */
export const ProblemDetailsWithErrorsSchema = ProblemDetailsSchema.extend({
  errors: z.array(ValidationErrorDetailSchema)
})

/**
 * Problem-details payload with field-level validation failures inferred from
 * the schema.
 */
export type ProblemDetailsWithErrors = z.output<typeof ProblemDetailsWithErrorsSchema>

export const PaginationSchema = z.object({
  hasMore: z.boolean(),
  limit: z.number().int().positive(),
  count: z.number().int().min(0),

  // Cursor-based navigation
  nextCursor: z.string().optional(),
  prevCursor: z.string().optional(),

  // Offset-based navigation
  offset: z.number().int().min(0).optional(),
  nextOffset: z.number().int().min(0).optional(),
  prevOffset: z.number().int().min(0).optional(),

  // Totals
  total: z.number().int().min(0).optional(),
  approxTotal: z.number().int().min(0).optional(),

  // Cursor expiration
  expiresAt: z.coerce.date().optional()
})

/**
 * Pagination metadata inferred from the schema.
 */
export type Pagination = z.output<typeof PaginationSchema>

/**
 * Base metadata schema - accepts arbitrary additional fields.
 */
export const DataMetadataSchema = z.object().catchall(z.unknown())

/**
 * Arbitrary metadata object inferred from the schema.
 */
export type DataMetadata = z.output<typeof DataMetadataSchema>

/**
 * LinkMap
 *
 * Normalized representation of RFC 8288-style links for a single response.
 *
 * - Keys are **link relation types** (`rel`): "self", "next", "prev", "first", "last", etc.
 * - Values are URI references (often relative paths like `/articles?page=2`).
 * - `self` is **required** and must be non-empty.
 * - Standard pagination rels (`first`, `last`, `next`, `prev`) are optional.
 * - Any additional rel (e.g. "describedby", "up", custom rels) is allowed via catchall.
 *
 * @example
 * const links = LinkMapSchema.parse({
 *   self: "/articles?offset=40&limit=20",
 *   first: "/articles?offset=0&limit=20",
 *   prev: "/articles?offset=20&limit=20",
 *   next: "/articles?offset=60&limit=20",
 *   last: "/articles?offset=120&limit=20",
 * })
 *
 * @example
 * const links = LinkMapSchema.parse({
 *   self: "/articles?offset=0&limit=20",
 *   describedby: "https://api.example.com/schemas/articles",
 *   profile: "https://api.example.com/profiles/pagination",
 * })
 */
export const LinkMapSchema = z.object({
  self: z.string().min(1, 'self link must be a non-empty URI reference'),
  first: z.string().min(1).optional(),
  last: z.string().min(1).optional(),
  next: z.string().min(1).optional(),
  prev: z.string().min(1).optional(),
}).catchall(z.string().min(1))

/**
 * RFC 8288-style link map inferred from the schema.
 */
export type LinkMap = z.output<typeof LinkMapSchema>

