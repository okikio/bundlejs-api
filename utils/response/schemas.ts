/** Standard headers schema. */
export const StandardHeadersSchema = z.object().catchall(z.string());

/**
 * Basic string header map inferred from the schema.
 */
export type StandardHeaders = z.output<typeof StandardHeadersSchema>

/** JSON response headers schema. */
export const JsonHeadersSchema = StandardHeadersSchema.extend({
  'Content-Type': z.union([z.literal(JSON_CONTENT_TYPE), z.string()])
})

/**
 * Standard JSON response headers inferred from the schema.
 */
export type JsonHeaders = z.output<typeof JsonHeadersSchema>

/** Pagination response headers schema. */
export const JsonHeadersWithLinksSchema = JsonHeadersSchema.extend({
  'Link': z.string(),
  'X-Total-Count': z.string().optional(),
  'X-Per-Page': z.string().optional(),
  'X-Page': z.string().optional(),
  'X-Total-Pages': z.string().optional(),
  'Preference-Applied': z.string().optional(),
  'Range-Unit': z.string().optional(),
  'Content-Range': z.string().optional()
})

/**
 * Pagination response headers inferred from the schema.
 */
export type JsonHeadersWithLinks = z.output<typeof JsonHeadersWithLinksSchema>

/** Problem-response headers schema. */
export const ProblemHeadersSchema = StandardHeadersSchema.extend({
  'Content-Type': z.literal(PROBLEM_JSON_CONTENT_TYPE)
})

/**
 * RFC 7807 problem-response headers inferred from the schema.
 */
export type ProblemHeaders = z.output<typeof ProblemHeadersSchema>

